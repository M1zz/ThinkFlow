def build(lang, scene):
    t = T[lang]
    now = time.time()
    at = lambda ago: now - ago - REF
    H, D = 3600, 86400
    after = scene == "thread"   # 이어서 생각하기를 한 번 마친 뒤
    a_entries = [
        dict(id=str(uuid.uuid4()), content=t["old"], layer=0, createdAt=at(5 * D), kind="thought"),
        dict(id=str(uuid.uuid4()), content=t["core"], layer=2, createdAt=at(4 * D + 2 * H), kind="thought"),
        dict(id=str(uuid.uuid4()), content=t["ref"], layer=0, createdAt=at(D + 23 * H), kind="reference", source="Claude"),
        dict(id=str(uuid.uuid4()), content=t["refined"], layer=1, createdAt=at(D), kind="thought"),
        dict(id=str(uuid.uuid4()), content=t["walk"], layer=0, createdAt=at(2 * H + 17 * 60), kind="thought"),
    ]
    if after:
        a_entries.append(dict(id=str(uuid.uuid4()), content=t["draft"], layer=0, createdAt=at(5 * 60 + 39), kind="thought"))
    a = dict(id=str(uuid.uuid4()), title=t["a_title"], emoji="🧠",
             bridge=dict(nextQuestion=t["bridge2"] if after else t["a_bridge"], updatedAt=at(60 if after else H + 5 * 60)),
             entries=a_entries, createdAt=at(5 * D), lastVisitedAt=at(60 if after else H + 5 * 60),
             totalThinkingSeconds=(52 if after else 45) * 60)
    b = dict(id=str(uuid.uuid4()), title=t["b_title"], emoji="🚀",
             bridge=dict(nextQuestion=t["b_bridge"], updatedAt=at(D + 2 * H)),
             entries=[dict(id=str(uuid.uuid4()), content=t["b_note"], layer=1, createdAt=at(D + 3 * H), kind="thought")],
             createdAt=at(9 * D), lastVisitedAt=at(D + 2 * H), totalThinkingSeconds=38 * 60)
    dump = [dict(id=str(uuid.uuid4()), content=t["dump"], createdAt=at(20 * 60))]
    return dict(threads=[a, b], dumpItems=dump, draft=t["draft"], bridgeDraft=t["bridge2"], dumpText="\n".join(t["lines"]))


if __name__ == "__main__":
    lang, scene, out = sys.argv[1:4]
    with open(out, "w", encoding="utf-8") as f:
        json.dump(build(lang, scene), f, ensure_ascii=False)
